export async function generateTestVault(app: App): Promise<void> {
  const existing = app.vault.getAbstractFileByPath(TEST_ROOT);
  if (existing && !(existing instanceof TFolder)) throw new Error(`${TEST_ROOT} существует, но это не папка`);
  if (!existing) await app.vault.createFolder(TEST_ROOT);

  let created = 0;
  let skipped = 0;
  for (const note of NOTES) {
    if (app.vault.getAbstractFileByPath(note.path)) { skipped++; continue; }
    await app.vault.create(note.path, note.content);
    created++;
  }
  new Notice(`Тестовый Vault создан: ${created} заметок${skipped ? `, ${skipped} уже существовали` : ""}. Переиндексируйте хранилище и попробуйте собрать структуру.`, 7000);
}

